using Microsoft.Extensions.VectorData;

namespace Qavren.Edge.VectorData.Tests.Records;

/// <summary>
/// A record whose storage names are all legal SQLite column names and none of them a plain word
/// SQLite reads bare: two keywords, a hyphen, a space, and one with an apostrophe and brackets in
/// it. The CLR names are ordinary, which is how such a record comes about - somebody mapping onto
/// column names they did not choose.
/// </summary>
public sealed class AwkwardNote
{
    /// <summary>The key, stored under a hyphenated name.</summary>
    [VectorStoreKey(StorageName = "note-id")]
    public string Key { get; set; } = "";

    /// <summary>Full-text, stored under a keyword SQLite will not read as a name.</summary>
    [VectorStoreData(StorageName = "From", IsFullTextIndexed = true)]
    public string Sender { get; set; } = "";

    /// <summary>Indexed and filterable, stored under a hyphenated name.</summary>
    [VectorStoreData(StorageName = "created-at", IsIndexed = true)]
    public string? Created { get; set; }

    /// <summary>Full-text, stored under two words.</summary>
    [VectorStoreData(StorageName = "message body", IsFullTextIndexed = true)]
    public string Body { get; set; } = "";

    /// <summary>Full-text, stored under a word that is an operator in both SQL and an FTS5 query.</summary>
    [VectorStoreData(StorageName = "OR", IsFullTextIndexed = true)]
    public string Alternative { get; set; } = "";

    /// <summary>Stored under a name with the characters other quoting styles are made of.</summary>
    [VectorStoreData(StorageName = "it's [odd]")]
    public string? Odd { get; set; }

    /// <summary>A four-wide pre-computed vector.</summary>
    [VectorStoreVector(4, DistanceFunction = DistanceFunction.CosineDistance)]
    public ReadOnlyMemory<float> Embedding { get; set; }
}

/// <summary>A full-text property under one of the two column names FTS5 keeps for itself.</summary>
public sealed class RankedNote
{
    /// <summary>The key.</summary>
    [VectorStoreKey]
    public string Key { get; set; } = "";

    /// <summary>FTS5's own <c>rank</c> column has this name, and no spelling gets a second one in.</summary>
    [VectorStoreData(IsFullTextIndexed = true)]
    public string Rank { get; set; } = "";

    /// <summary>A four-wide pre-computed vector.</summary>
    [VectorStoreVector(4)]
    public ReadOnlyMemory<float> Embedding { get; set; }
}

/// <summary>A storage name with a double quote in it, which no schema accepts.</summary>
public sealed class QuotedColumnRecord
{
    /// <summary>The key.</summary>
    [VectorStoreKey]
    public string Key { get; set; } = "";

    /// <summary>Stored under a name that would end its own quotation if written as it is.</summary>
    [VectorStoreData(StorageName = "we\"ird")]
    public string? Weird { get; set; }

    /// <summary>A four-wide pre-computed vector.</summary>
    [VectorStoreVector(4)]
    public ReadOnlyMemory<float> Embedding { get; set; }
}

/// <summary>An integer key the store assigns, which costs every record one more statement.</summary>
public sealed class AutoKeyVec
{
    /// <summary>Zero until the store assigns the next key.</summary>
    [VectorStoreKey(IsAutoGenerated = true)]
    public long Key { get; set; }

    /// <summary>A four-wide pre-computed vector.</summary>
    [VectorStoreVector(4, DistanceFunction = DistanceFunction.CosineDistance)]
    public ReadOnlyMemory<float> Embedding { get; set; }
}
